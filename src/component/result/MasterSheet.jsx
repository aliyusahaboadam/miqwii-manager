import { Document, Font, Page, pdf, StyleSheet, Text, View } from '@react-pdf/renderer';
import { useState } from 'react';
import { useDispatch } from 'react-redux';
import { getMasterSheetByClassId } from '../../redux/reducer/scoreSlice';
import { MasterSheetTable } from './MasterSheetTable';
import Oswald from './pdffonts/Oswald-VariableFont_wght.ttf';
import roboto from './pdffonts/RobotoRegular-3m4L.ttf';

Font.register({ family: 'Roboto', src: roboto });
Font.register({ family: 'Oswald', src: Oswald });

// ---------------------------------------------------------------------
// PDF Document
// ---------------------------------------------------------------------

const MyDocument = ({ resultsData }) => {
  const first = resultsData?.students?.[0];

  return (
    <Document>
      <Page size="A3" orientation="landscape" style={resultStyle.body}>
        <View style={resultStyle.logoAndHeadingContainer}>
          <View style={resultStyle.heading}>
            <Text style={resultStyle.schoolName}>
              {first?.school?.name || 'School Name'}
            </Text>
            <Text style={resultStyle.address}>
              {first?.school?.address || ''}
            </Text>
            <Text style={resultStyle.boldMottoText}>
              Motto:{' '}
              <Text style={resultStyle.motto}>{first?.school?.motto || ''}</Text>
            </Text>
            <Text style={resultStyle.boldText}>
              School Reg: No.:{' '}
              <Text style={resultStyle.address}>{first?.school?.regNo || ''}</Text>{' '}
              Tel:{' '}
              <Text style={resultStyle.address}>{first?.school?.contact || ''}</Text>
            </Text>
          </View>
        </View>

        <Text style={resultStyle.secondHeader}>
          MASTER SHEET FOR {first?.academicSession?.term || ''} TERM{' '}
          {first?.academicSession?.session || ''} ACADEMIC SESSION
        </Text>

        <MasterSheetTable data={resultsData} />

        <Text style={resultStyle.brandName}>~Generated By MiQwii Manager~</Text>
      </Page>
    </Document>
  );
};

// ---------------------------------------------------------------------
// React component
// ---------------------------------------------------------------------

const MasterSheet = ({ classId }) => {
  const dispatch = useDispatch();
  const [isGenerating, setIsGenerating] = useState(false);

  const generatePDF = async () => {
    const resultAction = await dispatch(getMasterSheetByClassId(classId));

    if (!getMasterSheetByClassId.fulfilled.match(resultAction)) {
      throw new Error('Failed to fetch master sheet');
    }

    const fetchedResults = resultAction.payload;
    if (!fetchedResults) {
      throw new Error('No data returned for this class.');
    }

    return pdf(<MyDocument resultsData={fetchedResults} />).toBlob();
  };

  const handleDownloadPDF = async () => {
    try {
      setIsGenerating(true);
      const blob = await generatePDF();
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.download = `mastersheet-${classId}.pdf`;
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(url);
    } catch (error) {
      alert(error.message || 'Error generating PDF. Please try again.');
    } finally {
      setIsGenerating(false);
    }
  };

  const handleViewPDF = async () => {
    try {
      setIsGenerating(true);
      const blob = await generatePDF();
      const url = URL.createObjectURL(blob);
      window.open(url, '_blank');
      setTimeout(() => URL.revokeObjectURL(url), 1000);
    } catch (error) {
      alert(error.message || 'Error generating PDF. Please try again.');
    } finally {
      setIsGenerating(false);
    }
  };

  return (
    <div style={{ display: 'flex', gap: '10px' }}>
      <button
        onClick={handleDownloadPDF}
        disabled={isGenerating}
        style={{
          padding: '10px 20px',
          backgroundColor: isGenerating ? '#ccc' : '#007bff',
          color: 'white',
          border: 'none',
          borderRadius: '4px',
          cursor: isGenerating ? 'not-allowed' : 'pointer',
        }}
      >
        {isGenerating ? 'Generating...' : 'Download Master Sheet'}
      </button>

      <button
        onClick={handleViewPDF}
        disabled={isGenerating}
        style={{
          padding: '10px 20px',
          backgroundColor: isGenerating ? '#ccc' : '#28a745',
          color: 'white',
          border: 'none',
          borderRadius: '4px',
          cursor: isGenerating ? 'not-allowed' : 'pointer',
        }}
      >
        {isGenerating ? 'Generating...' : 'View Master Sheet'}
      </button>
    </div>
  );
};

export default MasterSheet;

